export interface WorkbenchEnqueueItem {
  id: string;
  baseId: string;
  engine: string;
  params: unknown;
  seed: number;
  theme: number;
  category: string;
  catLabel: string;
  title: string;
  hook: string;
  description: string;
  tags: string[];
  filename: string;
  durationSec: number;
}

export interface WorkbenchChannelStatus {
  inChannel: boolean;
  status: 'available' | 'in_review' | 'scheduled' | 'published';
  specId: string | null;
  renderId: string | null;
  videoId: string | null;
  scheduledAt: string | null;
  mediaReady: boolean;
  mediaExt: 'mp4' | 'webm' | null;
  mediaBytes: number | null;
}

const ENGINE_TO_TEMPLATE: Record<string, string> = {
  hop: 'melody-bounce',
  rain: 'melody-bounce',
  ring: 'melody-bounce',
  multiply: 'melody-bounce',
  plinko: 'ball-sort',
  sorting: 'ball-sort',
  pendwave: 'pendulum-wave',
  orbits: 'orbit-sync',
};

export function toWorkbenchEnqueueItem(spec: WorkbenchSpec, durationSec: number): WorkbenchEnqueueItem {
  return {
    id: spec.id,
    baseId: spec.id.split('~')[0],
    engine: spec.engine,
    params: spec.params,
    seed: spec.seed,
    theme: spec.theme,
    category: spec.category,
    catLabel: spec.catLabel,
    title: spec.title,
    hook: spec.hook,
    description: spec.description,
    tags: spec.tags,
    filename: spec.filename,
    durationSec: Math.max(5, Math.min(180, Math.round(durationSec) || 25)),
  };
}

