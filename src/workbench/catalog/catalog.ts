const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 48);
const pick = <T,>(a: T[], v: number) => a[((v % a.length) + a.length) % a.length];
const fill = (s: string, m: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k) => String(m[k] ?? ''));
function hashStr(s: string) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

interface Def {
  id: string;
  engine: string;
  cat: string;
  params: (v: number) => unknown;
  vars?: Record<string, string | number>;
  titles: string[];
  hooks: string[];
  intro: string[];
  detail: string;
  extra?: string;
  tags: string[];
  hash: string;
  theme?: number;
}

const BASE_TAGS = ['shorts', 'satisfying', 'oddly satisfying', 'simulation', 'loop'];
const FOOTER = 'Every frame is generated by code — no camera, just math & physics. Sound is synthesized.\n👍 Like & subscribe for more satisfying physics, math and music loops.';

function def(d: Def): Recipe {
  const label = CATEGORIES.find((c) => c.id === d.cat)!.label;
  return {
    id: d.id,
    category: d.cat,
    catLabel: label,
    engine: d.engine,
    spec(v: number): VideoSpec {
      const vars = d.vars ?? {};
      let title = fill(pick(d.titles, v), vars);
      if (title.length > 100) title = title.slice(0, 99).trimEnd();
      const hook = fill(pick(d.hooks, v), vars);
      const desc = [
        fill(pick(d.intro, v), vars),
        '',
        fill(d.detail, vars),
        d.extra ? fill(d.extra, vars) : '',
        '',
        FOOTER,
        '',
        d.hash,
      ].filter((l, i, a) => !(l === '' && a[i - 1] === '')).join('\n');
      return {
        id: v === 0 ? d.id : `${d.id}~${v}`,
        engine: d.engine,
        params: d.params(v),
        seed: (hashStr(d.id) + v * 7919) >>> 0,
        theme: ((d.theme ?? hashStr(d.id) % 8) + v * 3) % 8,
        category: d.cat,
        catLabel: label,
        title,
        hook,
        description: desc,
        tags: [...new Set([...d.tags, ...BASE_TAGS])],
        filename: slug(d.id) + (v ? `-v${v + 1}` : ''),
      };
    },
  };
}

