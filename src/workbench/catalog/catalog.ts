const gcd = (a: number, b: number): number => (b ? gcd(b, a % b) : a);

export function buildCatalog(): Recipe[] {
  // 交错排列，让浏览时类型不重复
  const groups = [musicRecipes(), sortRecipes(), algoRecipes(), physRecipes(), mathRecipes()];
  const out: Recipe[] = [];
  const max = Math.max(...groups.map((g) => g.length));
  const ratio = groups.map((g) => g.length / max);
  const acc = groups.map(() => 0);
  const idx = groups.map(() => 0);
  for (let step = 0; step < max; step++) {
    groups.forEach((g, gi) => {
      acc[gi] += ratio[gi];
      while (acc[gi] >= 1 && idx[gi] < g.length) { out.push(g[idx[gi]++]); acc[gi] -= 1; }
    });
  }
  groups.forEach((g, gi) => { while (idx[gi] < g.length) out.push(g[idx[gi]++]); });
  return out;
}
