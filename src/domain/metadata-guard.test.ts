test('auditPublishMetadata flags AI slop cliches while allowing domain-grounded workbench recipes', () => {
  const slop = auditPublishMetadata({
    title: 'Satisfying Ball Plays Canon in D — Wait For It!',
    hookLine: '90% PICK THE WRONG ONE! Watch till the end!',
    description: 'Every frame is generated by code and every note is real audio. Like & subscribe!',
    tags: ['satisfying', 'shorts'],
  });
  assert.equal(slop.passed, false);
  const codes = new Set(slop.issues.map((i) => i.code));
  assert.ok(codes.has('POLICY_AI_SLOP_CLICHE'));

  const catalog = buildCatalog();
  for (const recipe of catalog) {
    const spec = recipe.spec(0);
    assert.equal(spec.title.includes('#'), false, `Title contains #: ${spec.title}`);
    const report = auditPublishMetadata({
      title: spec.title,
      hookLine: spec.hook,
      description: spec.description,
      tags: spec.tags,
    });
    const hasSlop = report.issues.some(
      (i) => i.code === 'POLICY_AI_SLOP_CLICHE' || i.code === 'AI_SLOP_FILLER'
    );
    assert.equal(hasSlop, false, `Recipe ${spec.id} triggered AI slop check: ${JSON.stringify(report.issues)}`);
  }
});

